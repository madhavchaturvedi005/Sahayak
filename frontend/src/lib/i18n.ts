export function daysLabel(value: number | null, lang: Lang = 'en') {
  if (value == null) return '—'
  if (lang === 'hi') {
    if (value < 1) return COPY.hi.dayLt1
    if (value === 1) return COPY.hi.day1
    const n = Number.isInteger(value) ? value : value.toFixed(1)
    return interpolate(COPY.hi.dayN, { n })
  }
  if (value < 1) return COPY.en.dayLt1
  if (value === 1) return COPY.en.day1
  const n = Number.isInteger(value) ? value : value.toFixed(1)
  return interpolate(COPY.en.dayN, { n })
}

export function formatDateLocale(value: string | Date, lang: Lang = 'en') {
  const date = typeof value === 'string' ? new Date(value) : value
  return date.toLocaleDateString(lang === 'hi' ? 'hi-IN' : 'en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  })
}

export function formatDateTimeLocale(value: string | Date, lang: Lang = 'en') {
  const date = typeof value === 'string' ? new Date(value) : value
  return date.toLocaleString(lang === 'hi' ? 'hi-IN' : 'en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  })
}
